#!/usr/bin/env python3
"""Render the authoritative ClickHouse migrations as a Kubernetes init Job."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
MIGRATIONS = ROOT / "deployments/clickhouse/migrations"
RUNNER = ROOT / "scripts/clickhouse/run-migrations.sh"
OUTPUT = (
    ROOT
    / "deployments/kubernetes/init-jobs/03a-clickhouse-authoritative-migrations.yaml"
)
IMAGE = (
    "docker.io/clickhouse/clickhouse-server@sha256:"
    "458f72c00e4abc80c2950d8070bc5723b538544d72ea4a6a58d9ff4f8fadf8d7"
)


def indent_block(value: str, spaces: int = 4) -> str:
    prefix = " " * spaces
    return "\n".join(prefix + line for line in value.rstrip("\n").splitlines())


def source_digest(files: list[Path]) -> str:
    digest = hashlib.sha256()
    for path in files:
        relative = path.relative_to(ROOT).as_posix()
        digest.update(hashlib.sha256(path.read_bytes()).hexdigest().encode("ascii"))
        digest.update(b"  ")
        digest.update(relative.encode("utf-8"))
        digest.update(b"\n")
    return digest.hexdigest()


def render() -> str:
    migrations = sorted(MIGRATIONS.glob("*.sql"))
    if not migrations:
        raise ValueError("authoritative ClickHouse migrations are absent")
    files = [RUNNER, *migrations]
    digest = source_digest(files)
    data_parts = [
        "  run-migrations.sh: |-\n" + indent_block(RUNNER.read_text(encoding="utf-8"))
    ]
    for migration in migrations:
        data_parts.append(
            f"  {migration.name}: |-\n"
            + indent_block(migration.read_text(encoding="utf-8"))
        )
    data = "\n".join(data_parts)
    rendered = f"""---
# Generated by scripts/clickhouse/render-kubernetes-migrations.py.
# Do not edit this file directly; the source of truth is the versioned
# migration directory and its checksum-enforcing runner.
apiVersion: v1
kind: ConfigMap
metadata:
  name: clickhouse-authoritative-migrations-{digest[:12]}
  namespace: middleware
  labels:
    app: clickhouse-schema-migrations
    traffic.analysis/schema-authority: t-ch-001
  annotations:
    traffic.analysis/source-sha256: "{digest}"
data:
{data}
---
apiVersion: batch/v1
kind: Job
metadata:
  name: init-clickhouse-authoritative-{digest[:12]}
  namespace: middleware
  labels:
    app: clickhouse-schema-migrations
    traffic.analysis/schema-authority: t-ch-001
  annotations:
    traffic.analysis/source-sha256: "{digest}"
    traffic.analysis/production-applied: "false"
spec:
  backoffLimit: 3
  ttlSecondsAfterFinished: 86400
  template:
    metadata:
      labels:
        app: clickhouse-schema-migrations
    spec:
      automountServiceAccountToken: false
      restartPolicy: OnFailure
      securityContext:
        seccompProfile: {{type: RuntimeDefault}}
      containers:
      - name: migration-runner
        image: {IMAGE}
        imagePullPolicy: IfNotPresent
        command: ["/bin/bash", "-ec"]
        args:
        - |-
          for host in $CLICKHOUSE_HOSTS; do
            ready=0
            for attempt in $(seq 1 60); do
              if clickhouse-client \
                --host "$host" \
                --user "$CLICKHOUSE_USER" \
                --password "$CLICKHOUSE_PASSWORD" \
                --query "EXISTS TABLE traffic.sessions_local" 2>/dev/null \
                | grep -qx '1'; then
                ready=1
                break
              fi
              sleep 5
            done
            if [ "$ready" -ne 1 ]; then
              echo "ClickHouse baseline schema is not ready on $host" >&2
              exit 4
            fi
          done
          exec /migrations/run-migrations.sh
        env:
        - name: CLICKHOUSE_HOSTS
          value: "clickhouse-1.middleware.svc clickhouse-replica-0.clickhouse-replica.middleware.svc clickhouse-2.middleware.svc clickhouse-replica-1.clickhouse-replica.middleware.svc"
        - name: CLICKHOUSE_USER
          value: "default"
        - name: CLICKHOUSE_MIGRATIONS
          value: "/migrations"
        - name: CLICKHOUSE_CLIENT
          value: "clickhouse-client"
        - name: CLICKHOUSE_PASSWORD
          valueFrom:
            secretKeyRef:
              name: traffic-credentials
              key: CLICKHOUSE_PASSWORD
        resources:
          requests: {{cpu: "100m", memory: "128Mi"}}
          limits: {{cpu: "500m", memory: "512Mi"}}
        securityContext:
          allowPrivilegeEscalation: false
          capabilities: {{drop: ["ALL"]}}
          readOnlyRootFilesystem: true
        volumeMounts:
        - name: migrations
          mountPath: /migrations
          readOnly: true
        - name: tmp
          mountPath: /tmp
      volumes:
      - name: migrations
        configMap:
          name: clickhouse-authoritative-migrations-{digest[:12]}
          defaultMode: 365
      - name: tmp
        emptyDir: {{}}
"""
    if len(rendered.encode("utf-8")) >= 900_000:
        raise ValueError("rendered migration ConfigMap is too close to Kubernetes size limit")
    return rendered


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            print(f"STALE: {OUTPUT.relative_to(ROOT)}")
            return 1
        print(f"PASS: {OUTPUT.relative_to(ROOT)}")
        return 0
    OUTPUT.write_text(expected, encoding="utf-8")
    print(OUTPUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
