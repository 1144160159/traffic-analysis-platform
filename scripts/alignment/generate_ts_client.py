#!/usr/bin/env python3
"""Generate the small alignment TypeScript client from the OpenAPI source."""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "contracts/openapi/alignment-v1.openapi.json"
OUTPUT = ROOT / "web/ui/src/generated/alignmentClient.ts"
METHODS = {"get", "post", "put", "patch", "delete"}


def render() -> str:
    document = json.loads(SOURCE.read_text(encoding="utf-8"))
    operations: list[tuple[str, str, str]] = []
    for path, path_item in document["paths"].items():
        for method, operation in path_item.items():
            if method in METHODS:
                operations.append((operation["operationId"], method.upper(), path))
    operations.sort()
    lines = [
        "/* This file is generated by scripts/alignment/generate_ts_client.py. */",
        "/* Do not edit by hand. */",
        "",
        "import { api } from '@/services/api';",
        "",
        "export type AlignmentFieldError = {",
        "  field: string;",
        "  code: string;",
        "  message: string;",
        "};",
        "",
        "export type AlignmentError = {",
        "  code: string;",
        "  message: string;",
        "  trace_id: string;",
        "  retryable: boolean;",
        "  field_errors?: AlignmentFieldError[];",
        "  operation_id?: string;",
        "  current_revision?: number;",
        "  projection_status?: string;",
        "  status_url?: string;",
        "  expected_consistency_window?: string;",
        "};",
        "",
        "export type AlignmentMeta = {",
        "  contract_version: number;",
        "  schema_version: number;",
        "  snapshot_id: string;",
        "  as_of: string;",
        "  generated_at: string;",
        "  trace_id: string;",
        "  result_code: string;",
        "  operation_id?: string;",
        "  tenant_id?: string;",
        "  partial: boolean;",
        "  missing_sections: string[];",
        "  source_watermarks: Record<string, string>;",
        "  projection_status?: string;",
        "};",
        "",
        "export type AlignmentEnvelope<T = unknown> = {",
        "  data: T;",
        "  meta: AlignmentMeta;",
        "  error: AlignmentError | null;",
        "};",
        "",
        "export type AlignmentRequest = {",
        "  path?: Record<string, string>;",
        "  query?: Record<string, string | number | boolean | undefined>;",
        "  body?: unknown;",
        "  idempotencyKey?: string;",
        "};",
        "",
        "const resolvePath = (template: string, values: Record<string, string> = {}) =>",
        "  template.replace(/\\{([^}]+)\\}/g, (_, key: string) => encodeURIComponent(values[key] ?? ''));",
        "",
    ]
    for operation_id, method, path in operations:
        lines.extend(
            [
                f"export async function {operation_id}(request: AlignmentRequest = {{}}) {{",
                f"  const path = resolvePath('{path}', request.path);",
                "  const headers = request.idempotencyKey ? { 'Idempotency-Key': request.idempotencyKey } : undefined;",
                f"  const response = await api.request({{ method: '{method}', url: path, params: request.query, data: request.body, headers }});",
                "  return response.data;",
                "}",
                "",
            ]
        )
    return "\n".join(lines)


def main() -> int:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
